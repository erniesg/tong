// Builds the Relationship Lab and the cozy world's copy of the engine and scenes.
//   node scripts/build-relationship-lab.mjs [--fragment <out.html>] [--check]
// Writes public/studio/relationship/index.html (full document) and
// public/cozy/js/relationship/{engine,scenes}.js (the cozy 3D world plays these).
// --fragment also writes the body-only lab used for the published artifact.
// --check writes nothing and fails if any output is stale.
import { existsSync, readFileSync, readdirSync, statSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import ts from 'typescript';

const app = join(dirname(fileURLToPath(import.meta.url)), '..');
const content = join(app, 'lib/content');
const SKIP = new Set(['index.ts', 'bids.ts']);
const walk = (dir) =>
  readdirSync(dir).flatMap((f) => {
    const p = join(dir, f);
    if (statSync(p).isDirectory()) return walk(p);
    return p.endsWith('.ts') && !p.endsWith('.test.ts') && !SKIP.has(f) ? [p] : [];
  });
const load = async (p) => import(pathToFileURL(p).href);

const scenes = [];
for (const f of walk(join(content, 'routes')).sort()) scenes.push((await load(f)).module);
const order = { story: 0, ambient: 1 };
scenes.sort((a, b) => order[a.scene.kind] - order[b.scene.kind] || a.scene.id.localeCompare(b.scene.id));
const threads = [];
for (const f of walk(join(content, 'kakao')).sort()) threads.push((await load(f)).module);
const canon = {
  characters: [
    (await load(join(content, 'canon/haeun.ts'))).HAEUN_CANON,
    (await load(join(content, 'canon/sua.ts'))).SUA_CANON,
    (await load(join(content, 'canon/jin.ts'))).JIN_CANON,
    ...(({ DOHEE_CANON, DAON_CANON, BORAM_CANON, YUNSEO_CANON }) => [DOHEE_CANON, DAON_CANON, BORAM_CANON, YUNSEO_CANON])(await load(join(content, 'canon/cohort.ts'))),
  ],
  world: (await load(join(content, 'canon/world.ts'))).SEOUL_WORLD,
};

const engineSrc = readFileSync(join(app, 'lib/relationship/engine.ts'), 'utf8');
const engineModule = ts.transpileModule(engineSrc, {
  compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext, verbatimModuleSyntax: false },
}).outputText;
const engine = engineModule.replace(/^export \{\};?\s*$/m, '');
const HEADER = '// Generated by scripts/build-relationship-lab.mjs from lib/relationship and lib/content. Do not edit.\n';

const data = JSON.stringify({ scenes, threads, canon }).replace(/</g, '\\u003c');
const fragment = readFileSync(join(app, 'lib/relationship/harness/template.html'), 'utf8')
  .replace('/*__ENGINE__*/', () => engine)
  .replace('/*__DATA__*/', () => data);

const full = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
</head>
<body>
${fragment}
</body>
</html>
`;
// The cozy world needs scenes only (no presets, threads or canon).
const cozyScenes = Object.fromEntries(scenes.map((m) => [m.scene.id, m.scene]));
const outputs = {
  'public/studio/relationship/index.html': full,
  'public/cozy/js/relationship/engine.js': HEADER + engineModule,
  'public/cozy/js/relationship/scenes.js': `${HEADER}export const SCENES = ${JSON.stringify(cozyScenes, null, 1)};\n`,
};
if (process.argv.includes('--check')) {
  const stale = Object.entries(outputs).filter(([p, s]) => !existsSync(join(app, p)) || readFileSync(join(app, p), 'utf8') !== s).map(([p]) => p);
  if (stale.length) {
    console.error(`stale: ${stale.join(', ')}. Run node scripts/build-relationship-lab.mjs`);
    process.exit(1);
  }
  console.log('relationship outputs are up to date');
} else {
  for (const [p, s] of Object.entries(outputs)) {
    mkdirSync(dirname(join(app, p)), { recursive: true });
    writeFileSync(join(app, p), s);
  }
  const i = process.argv.indexOf('--fragment');
  if (i > 0) writeFileSync(process.argv[i + 1], fragment);
  console.log(`lab: ${scenes.length} scenes, ${threads.length} threads (${Math.round(full.length / 1024)} KB); cozy: ${Object.keys(cozyScenes).length} scenes`);
}
